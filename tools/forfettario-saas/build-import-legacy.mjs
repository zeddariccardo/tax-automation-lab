// Reproducible extraction from the frozen public tool. Never edits that tool.
// No application startup, localStorage/IndexedDB access, network or fiscal totals.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
// Build-time parser already shipped with the existing Playwright dependency.
const {babelParse}=createRequire(import.meta.url)('../../node_modules/playwright/lib/transform/babelBundle.js');
const html=(await readFile(new URL('../forfettario/index.html',import.meta.url),'utf8')).replaceAll('\r\n','\n');
const digest=createHash('sha256').update(html).digest('hex');
assert.equal(digest,'a6cee27a0af02d32fbbfb7586c7204908a2aece529a414aa031bd3489b34e497');
const script=id=>{const start=html.indexOf('<script id="'+id+'">')+('<script id="'+id+'">').length;
 assert.ok(start>0);return html.slice(start,html.indexOf('</script>',start));};
let engine=script('forfettario-engine-v6');
const auto=engine.indexOf('const shouldAutoRun=');assert.ok(auto>0);
engine=engine.slice(0,auto)+'})(root);';
const xmlSource=script('forfettario-fatturapa-import');
const xml=xmlSource.slice(0,xmlSource.indexOf('if(new URLSearchParams(location.search)'))+'})(root);';
const ui=script('forfettario-tal-ui-v8'),lines=ui.split('\n');
const names=['parseCsvRows','normalizeBulkSheetRows','autoMapBulkHeaders','classifyBulkInvoiceRow','bulkWorksheetMatrix',
 'validateAppState','verifyChecksum','canonicalJson','validateProfessionalIdentity','professionalIdentityFromState'];
const ast=babelParse(ui,'legacy-ui.js',false);
const functions=new Map(ast.program.body[0].expression.callee.body.body.filter(n=>n.type==='FunctionDeclaration').map(n=>[n.id.name,ui.slice(n.start,n.end)]));
const included=new Map();
function include(name){if(included.has(name))return;const fn=functions.get(name);assert.ok(fn,'Missing function '+name);included.set(name,fn);
 for(const other of functions.keys())if(new RegExp('\\b'+other+'\\b').test(fn)&&other!==name)include(other);}
names.forEach(include);
const bulk=ui.slice(ui.indexOf('const BULK_INVOICE_FIELDS='),ui.indexOf('const BULK_MAPPING_PROVIDERS='));
const limits=lines.find(l=>l.startsWith('const BULK_IMPORT_LIMITS='));
const liquidity=lines.find(l=>l.startsWith('const LIQUIDITY_CATEGORIES='));assert.ok(liquidity);
const output=`// GENERATED by build-import-legacy.mjs from S01 sha256 ${digest}\n// Pure legacy document/import logic, isolated from the public application's UI and storage.\nconst root=Object.create(null);\n${engine}\n${xml}\nconst E=root.ForfettarioEngine,F=root.ForfettarioFatturaPA;\nconst clone=value=>JSON.parse(JSON.stringify(value));\nconst UI_SCHEMA='forfettario-pro-personal-v2',SUPPORTED_YEARS=[2025,2026];\n${liquidity}\n${bulk}\n${limits}\n${[...included.values()].join('\n')}\nexport {E,F,BULK_INVOICE_FIELDS,${names.join(',')}};\n`;
assert.doesNotMatch(output,/\b(?:localStorage|indexedDB|fetch)\s*[.(]/);
babelParse(output,'import-legacy.generated.js',true);
const target=new URL('./import-legacy.generated.js',import.meta.url);
if(process.argv.includes('--check'))assert.equal(await readFile(target,'utf8'),output,'Generated legacy importer drift');
else await writeFile(target,output);
console.log('S13 frozen parser extraction verified; '+included.size+' pure helpers; '+Buffer.byteLength(output)+' bytes');
